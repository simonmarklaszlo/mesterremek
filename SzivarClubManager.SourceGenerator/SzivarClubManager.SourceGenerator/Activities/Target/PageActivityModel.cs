using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SzivarClubManager.SourceGenerator.Activities.Target;

public class PageActivityModel : ITarget
{
    private const string ActivityViewModelNamespace = "SzivarClubManager.ViewModels.Activities.PageActivity";
    private const string PageActivityAttribute = "SzivarClubManager.SourceGeneration.PageActivityAttribute";


    public string ModelType { get; }
    public string ViewModelType => $"{ModelType}PageActivityDataViewModel";


    public PageActivityModel(string modelType)
    {
        ModelType = modelType;
    }

    public PageActivity ToPageActivity() => new ($"{ModelType}s", ViewModelType, ModelType);
    public string GenerateViewModelSource()
    {
        StringBuilder sb = new();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using SzivarClubManager.Datasources;");
        sb.AppendLine("using SzivarClubManager.Models;");
        sb.AppendLine("using SzivarClubManager.SourceGeneration;");
        sb.AppendLine("using SzivarClubManager.Datasources.Pagination;");
        sb.AppendLine("");
        sb.AppendLine($"namespace {ActivityViewModelNamespace};");
        sb.AppendLine("");
        sb.AppendLine($"[PageActivityCollectionItem(typeof({ModelType}))]");
        sb.AppendLine($"public class {ViewModelType}(");
        sb.AppendLine($"    IPageFactory<{ModelType}> factory");
        // sb.AppendLine("    IDataSource dataSource,");
        // sb.AppendLine("    Func<int, int, Task<bool>> pageExistsFunc,");
        // sb.AppendLine("    Func<int, Task<int>> lastPageFunc,");
        // sb.AppendLine($"    Func<int, int, Task<{ModelType}[]>> loadPageFunc");
        sb.AppendLine($") : PageActivityDataViewModel<{ModelType}>(factory);");

        return sb.ToString();
    }

    public static PageActivityModel? IsTarget(GeneratorSyntaxContext context)
    {
        if (context.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)context.Node) is not INamedTypeSymbol typeSymbol) return null;
        var attributeSymbol = context.SemanticModel.Compilation.GetTypeByMetadataName(PageActivityAttribute);
        if (attributeSymbol is null) return null;

        foreach (var attribute in typeSymbol.GetAttributes())
        {
            if (!SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, attributeSymbol))
            {
                continue;
            }

            if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Value is true)
            {
                return new PageActivityModel(typeSymbol.Name);
            }
        }

        return null;
    }
}