using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using SzivarClubManager.SourceGenerator.Factories.Target;

namespace SzivarClubManager.SourceGenerator.Factories;

[Generator]
public class Generator : IIncrementalGenerator
{
    //TODO : warn on type collision
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var targetCandidates = context.SyntaxProvider
            .CreateSyntaxProvider(
                (node, _) => node is TypeDeclarationSyntax { AttributeLists.Count: > 0 },
                (ctx, _) => GetTarget(ctx)
            )
            .Where(t => t is not null)
            .Select((t, _) => t!);

        context.RegisterSourceOutput(targetCandidates.Collect(), (ctx, factories) =>
        {
            ctx.AddSource(
                "FactoryProvider.g.cs",
                GenerateFactoryCollection(factories)
            );
        });
    }

    private static Factory? GetTarget(GeneratorSyntaxContext context)
    {
        const string factoryOfAttribute = "SzivarClubManager.SourceGeneration.FactoryOfAttribute";
        const string fakeFactoryOfAttribute = "SzivarClubManager.SourceGeneration.FakeFactoryOfAttribute";

        if (context.SemanticModel.GetDeclaredSymbol((TypeDeclarationSyntax)context.Node) is not INamedTypeSymbol typeSymbol) return null;
        var factoryAttributeSymbol = context.SemanticModel.Compilation.GetTypeByMetadataName(factoryOfAttribute);
        var fakeFactoryAttributeSymbol = context.SemanticModel.Compilation.GetTypeByMetadataName(fakeFactoryOfAttribute);
        if (factoryAttributeSymbol is null || fakeFactoryAttributeSymbol is null) return null;

        foreach (var attribute in typeSymbol.GetAttributes())
        {
            if (!SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, factoryAttributeSymbol) &&
                !SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, fakeFactoryAttributeSymbol))
            {
                continue;
            }

            if (
                attribute.ConstructorArguments.Length == 1 &&
                attribute.ConstructorArguments[0] is { Value: INamedTypeSymbol fakeModelTypeSymbol }
            )
            {
                return new FakeFactory(
                    new TypeName(typeSymbol.Name, typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)),
                    new TypeName(fakeModelTypeSymbol.Name, fakeModelTypeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                );
            }

            if (
                attribute.ConstructorArguments.Length == 2 &&
                attribute.ConstructorArguments[0] is { Value: INamedTypeSymbol modelTypeSymbol } &&
                attribute.ConstructorArguments[1].Value is bool databaseRequired
            )
            {
                return new Factory(
                    new TypeName(typeSymbol.Name, typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)),
                    new TypeName(modelTypeSymbol.Name, modelTypeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)),
                    databaseRequired
                );
            }
        }

        return null;
    }

    private static string GenerateFactoryCollection(ImmutableArray<Factory> factories)
    {
        const string databaseConnectionVariableName = "connection";

        var orderedFactories = factories
            .OrderBy(x => x.ModelTypeName.Name)
            .ToImmutableArray();

        StringBuilder sb = new();

        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using SzivarClubManager.Models;");
        sb.AppendLine("using SzivarClubManager.Datasources.Database;");
        sb.AppendLine("using SzivarClubManager.Datasources.Database.Factories;");
        sb.AppendLine("using SzivarClubManager.Datasources.Fake.Factories;");
        sb.AppendLine();
        sb.AppendLine("namespace SzivarClubManager.Datasources;");
        sb.AppendLine();
        sb.AppendLine("public partial class FactoryProvider");
        sb.AppendLine("{");
        // normal
        sb.AppendLine(
            $"    private static partial Dictionary<Type, IFactory> GetGeneratedFactoriesMap(DatabaseConnection {databaseConnectionVariableName}) => new Dictionary<Type, IFactory>()"
        );
        sb.AppendLine("    {");
        if (factories.Length == 0) sb.AppendLine("        // No factories found");

        foreach (var f in orderedFactories.Where(x => x.GetType() == typeof(Factory)))
        {
            sb.AppendLine($"       {{ typeof({f.ModelTypeName.Name}), {f.InstanceCreation(databaseConnectionVariableName)} }},");
        }

        sb.AppendLine("    };");
        sb.AppendLine();

        //fake
        sb.AppendLine(
            "    private static partial Dictionary<Type, IFactory> GetGeneratedFakeFactoriesMap() => new Dictionary<Type, IFactory>()"
        );
        sb.AppendLine("    {");
        if (factories.Length == 0) sb.AppendLine("        // No fake factories found");

        foreach (var f in orderedFactories.OfType<FakeFactory>())
        {
            sb.AppendLine($"       {{ typeof({f.ModelTypeName.Name}), {f.InstanceCreation()} }},");
        }

        sb.AppendLine("    };");
        sb.AppendLine("}");

        return sb.ToString();
    }
}